//! wasm-bindgen in an app's web runtime: an app whose crates use it
//! (`web-sys`, `js-sys`: a WebSocket, the DOM) links imports that only
//! wasm-bindgen's JS glue provides. `nsh` finds `wasm-bindgen` in the web
//! runtime's dependencies ([`version_in`]), runs the `wasm-bindgen` CLI
//! of the same version on the built module ([`process`]) and ships the glue
//! next to `nsh.js`, which merges the glue's imports with its own
//! (`nsh`, `env`) and runs the glue's setup before the app starts. A runtime
//! without wasm-bindgen is built and served as before.
//!
//! The glue is wasm-bindgen's `--target web` output, adapted ([`adapt`]):
//! the imports wasm-bindgen does not provide (the `nsh` module) are not ES
//! modules but `nsh.js`' own, and its import table and setup are exported for
//! `nsh.js` to call.

use std::{
    path::{Path, PathBuf},
    process::Command,
};

use anyhow::{Context as _, bail};

/// The file the glue is served and packaged as, next to `nsh.js`.
pub(crate) const GLUE: &str = "nsh-bindgen.js";

/// The `wasm-bindgen` CLI to run: `NSH_WASM_BINDGEN`, else the one on `PATH`.
fn cli() -> std::ffi::OsString {
    std::env::var_os("NSH_WASM_BINDGEN").unwrap_or_else(|| "wasm-bindgen".into())
}

/// The version of the `wasm-bindgen` crate the package `root` links for
/// `wasm32-unknown-unknown`, in `metadata` (`cargo metadata
/// --filter-platform wasm32-unknown-unknown`): `None` when it does not.
pub(crate) fn version_in(metadata: &serde_json::Value, root: &str) -> Option<String> {
    let packages = metadata["packages"].as_array()?;
    let root_id = packages.iter().find(|p| p["name"].as_str() == Some(root))?["id"].as_str()?;
    let nodes = metadata["resolve"]["nodes"].as_array()?;
    let node = |id: &str| nodes.iter().find(|n| n["id"].as_str() == Some(id));
    let mut seen = vec![root_id.to_owned()];
    let mut next = 0;
    while let Some(id) = seen.get(next).cloned() {
        next += 1;
        let Some(node) = node(&id) else { continue };
        for dep in node["deps"].as_array().into_iter().flatten() {
            // Normal dependencies only: a build script's or a test's
            // wasm-bindgen is not in the module.
            let normal = dep["dep_kinds"]
                .as_array()
                .into_iter()
                .flatten()
                .any(|k| k["kind"].is_null());
            let Some(dep_id) = dep["pkg"].as_str() else {
                continue;
            };
            if normal && !seen.iter().any(|s| s == dep_id) {
                seen.push(dep_id.to_owned());
            }
        }
    }
    packages
        .iter()
        .find(|p| {
            p["name"].as_str() == Some("wasm-bindgen")
                && p["id"]
                    .as_str()
                    .is_some_and(|id| seen.iter().any(|s| s == id))
        })
        .and_then(|p| p["version"].as_str())
        .map(str::to_owned)
}

/// The version `wasm-bindgen --version` printed (`wasm-bindgen 0.2.129`).
fn cli_version(output: &str) -> Option<&str> {
    output.split_whitespace().nth(1)
}

/// Checks that the `wasm-bindgen` CLI that printed `output` (`None`: none
/// ran) is `version`, the crate's: the glue and the module's imports are
/// generated by the two together.
pub(crate) fn check_cli(version: &str, output: Option<&str>) -> anyhow::Result<()> {
    let install = format!("cargo install wasm-bindgen-cli --version {version} --locked");
    match output.and_then(cli_version) {
        Some(cli) if cli == version => Ok(()),
        Some(cli) => bail!(
            "the app's web runtime links wasm-bindgen {version}, and the wasm-bindgen CLI is {cli}: they must be the same version ({install})"
        ),
        None => bail!(
            "the app's web runtime links wasm-bindgen {version}, which needs the wasm-bindgen CLI of that version: {install}"
        ),
    }
}

/// Runs the `wasm-bindgen` CLI (`version`, checked first) on `module`,
/// writing into `out` the module to load and the glue ([`adapt`]ed) as
/// `<name>.wasm` and `<name>-bindgen.js`; returns their paths.
pub(crate) fn process(
    module: &Path,
    version: &str,
    out: &Path,
    name: &str,
) -> anyhow::Result<(PathBuf, PathBuf)> {
    let printed = Command::new(cli())
        .arg("--version")
        .output()
        .ok()
        .filter(|o| o.status.success())
        .map(|o| String::from_utf8_lossy(&o.stdout).into_owned());
    check_cli(version, printed.as_deref())?;
    let dir = out.join("bindgen");
    let mut command = Command::new(cli());
    command
        .args(["--target", "web", "--no-typescript", "--out-dir"])
        .arg(&dir)
        .args(["--out-name", name])
        .arg(module);
    let step = crate::ui::Step::start("running wasm-bindgen on the web runtime");
    let (status, output) = crate::ui::capture(&mut command, |_| {}).context("run wasm-bindgen")?;
    if !status.success() {
        return Err(crate::ui::failure("running wasm-bindgen failed", output));
    }
    step.done(format!("ran wasm-bindgen {version} on the web runtime"));
    let wasm = out.join(format!("{name}.wasm"));
    std::fs::copy(dir.join(format!("{name}_bg.wasm")), &wasm)
        .with_context(|| format!("copy wasm-bindgen's module to {}", wasm.display()))?;
    let glue_path = out.join(format!("{name}-bindgen.js"));
    let glue = std::fs::read_to_string(dir.join(format!("{name}.js")))
        .context("read wasm-bindgen's glue")?;
    std::fs::write(&glue_path, adapt(&glue)?)
        .with_context(|| format!("write {}", glue_path.display()))?;
    Ok((wasm, glue_path))
}

/// The glue wasm-bindgen wrote (`--target web`), for `nsh.js`: an import of
/// a module wasm-bindgen does not provide (`import * as import1 from
/// "nsh"`, the module's own imports, which `nsh.js` gives) becomes an empty
/// object `nsh.js` fills; and the import table (`__wbg_get_imports`) and
/// setup (`__wbg_finalize_init`) are exported, as `__nsh_imports` and
/// `__nsh_finalize`.
pub(crate) fn adapt(glue: &str) -> anyhow::Result<String> {
    for function in [
        "function __wbg_get_imports(",
        "function __wbg_finalize_init(",
    ] {
        if !glue.contains(function) {
            bail!(
                "wasm-bindgen's glue has no {}: nsh knows the glue of wasm-bindgen 0.2.1xx (--target web)",
                function
                    .trim_start_matches("function ")
                    .trim_end_matches('(')
            );
        }
    }
    let mut out = String::with_capacity(glue.len() + 128);
    for line in glue.lines() {
        match foreign_import(line) {
            Some(binding) => out.push_str(&format!("const {binding} = {{}};")),
            None => out.push_str(line),
        }
        out.push('\n');
    }
    out.push_str(
        "export { __wbg_get_imports as __nsh_imports, __wbg_finalize_init as __nsh_finalize };\n",
    );
    Ok(out)
}

/// The binding of `line` when it imports a module that is not a file
/// (`import * as import1 from "nsh"`): one of the module's own imports.
fn foreign_import(line: &str) -> Option<&str> {
    let rest = line.trim().strip_prefix("import * as ")?;
    let (binding, specifier) = rest.split_once(" from ")?;
    let specifier = specifier
        .trim()
        .trim_end_matches(';')
        .trim_matches(['"', '\'']);
    (!specifier.starts_with("./") && !specifier.starts_with("../") && !specifier.starts_with('/'))
        .then_some(binding.trim())
}

#[cfg(test)]
mod tests {
    use super::{adapt, check_cli, version_in};

    /// `cargo metadata` of a workspace whose `web` depends on `app`, which
    /// depends on `wasm-bindgen` as `kind` (`null`: normal).
    fn metadata(kind: serde_json::Value) -> serde_json::Value {
        serde_json::json!({
            "packages": [
                { "name": "web", "id": "web 0.0.0", "version": "0.0.0" },
                { "name": "app", "id": "app 0.1.0", "version": "0.1.0" },
                { "name": "wasm-bindgen", "id": "wasm-bindgen 0.2.129", "version": "0.2.129" },
                { "name": "serde", "id": "serde 1.0.0", "version": "1.0.0" },
            ],
            "resolve": { "nodes": [
                { "id": "web 0.0.0", "deps": [
                    { "pkg": "app 0.1.0", "dep_kinds": [{ "kind": null }] },
                    { "pkg": "serde 1.0.0", "dep_kinds": [{ "kind": null }] },
                ] },
                { "id": "app 0.1.0", "deps": [
                    { "pkg": "wasm-bindgen 0.2.129", "dep_kinds": [{ "kind": kind }] },
                ] },
                { "id": "wasm-bindgen 0.2.129", "deps": [] },
                { "id": "serde 1.0.0", "deps": [] },
            ] },
        })
    }

    #[test]
    fn wasm_bindgen_is_found_in_the_runtime_s_dependencies() {
        let normal = metadata(serde_json::Value::Null);
        assert_eq!(version_in(&normal, "web").as_deref(), Some("0.2.129"));
        // Not the module's: a test's or a build script's.
        assert_eq!(version_in(&metadata("dev".into()), "web"), None);
        assert_eq!(version_in(&metadata("build".into()), "web"), None);
        // Not linked by the runtime at all.
        assert_eq!(version_in(&normal, "serde"), None);
        assert_eq!(version_in(&normal, "missing"), None);
    }

    #[test]
    fn wasm_bindgen_cli_must_be_the_crate_s_version() {
        assert!(check_cli("0.2.129", Some("wasm-bindgen 0.2.129\n")).is_ok());
        let other = check_cli("0.2.129", Some("wasm-bindgen 0.2.126"))
            .unwrap_err()
            .to_string();
        assert!(other.contains("links wasm-bindgen 0.2.129"), "{other}");
        assert!(other.contains("the wasm-bindgen CLI is 0.2.126"), "{other}");
        assert!(
            other.contains("cargo install wasm-bindgen-cli --version 0.2.129 --locked"),
            "{other}"
        );
        let none = check_cli("0.2.129", None).unwrap_err().to_string();
        assert!(
            none.contains("cargo install wasm-bindgen-cli --version 0.2.129"),
            "{none}"
        );
    }

    #[test]
    fn wasm_bindgen_glue_takes_nsh_s_imports_from_nsh_js() {
        let glue = "import * as import1 from \"nsh\"\n\
                    import * as import2 from './snippets/x.js';\n\
                    function __wbg_get_imports() {\n    return { \"./a_bg.js\": import0, \"nsh\": import1 };\n}\n\
                    function __wbg_finalize_init(instance, module) {}\n\
                    export { initSync, __wbg_init as default };\n";
        let adapted = adapt(glue).unwrap();
        assert!(adapted.starts_with("const import1 = {};\n"), "{adapted}");
        // Files the glue ships with stay imports.
        assert!(
            adapted.contains("import * as import2 from './snippets/x.js';"),
            "{adapted}"
        );
        assert!(adapted.ends_with(
            "export { __wbg_get_imports as __nsh_imports, __wbg_finalize_init as __nsh_finalize };\n"
        ));
        // Another shape of glue is refused, not shipped broken.
        let error = adapt("export default function init() {}")
            .unwrap_err()
            .to_string();
        assert!(error.contains("__wbg_get_imports"), "{error}");
    }
}
