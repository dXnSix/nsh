//! The bundler's part of the TypeScript declarations of `.nsh/types` (the
//! rest is nsh's modules', from `nsh_js::type_definitions`): what the asset
//! imports the bundler loads give (`assets.d.ts`). Apps find them through
//! their `tsconfig.json` ([`TSCONFIG`], extending [`TSCONFIG_BASE`]) and
//! need no `node_modules`.

/// `tsconfig.json` of a new app (`nsh init`): nsh's settings come from
/// [`TSCONFIG_BASE`], which every command that builds the app writes to
/// `.nsh/tsconfig.json`, so a new `lib` or path reaches existing apps
/// without an edit of theirs; the app's own settings go here, over them.
pub const TSCONFIG: &str = r#"{
  "extends": "./.nsh/tsconfig.json",
  "include": ["**/*.ts", "**/*.tsx"]
}
"#;

/// `.nsh/tsconfig.json`, which the app's `tsconfig.json` ([`TSCONFIG`])
/// extends: resolves `nsh` and the app's own native modules (`nsh.json`
/// `"rust"`) to `.nsh/types` (other imports fall back to `node_modules`),
/// JSX to nsh's (`nsh/jsx-runtime`), and declares the globals and asset
/// imports. Paths and files are relative to `.nsh`, where it is.
pub const TSCONFIG_BASE: &str = r#"// Generated by nsh, which keeps it current: the TypeScript settings of
// an nsh app. The app's tsconfig.json extends it; set your own there.
{
  "compilerOptions": {
    "target": "ES2023",
    "lib": ["ES2023", "ESNext.Disposable"],
    "module": "ESNext",
    "moduleResolution": "Bundler",
    "jsx": "preserve",
    "jsxImportSource": "nsh",
    "strict": true,
    "noEmit": true,
    "isolatedModules": true,
    "skipLibCheck": true,
    "types": [],
    "paths": {
      "nsh": ["./types/nsh/index.d.ts"],
      "nsh/*": ["./types/nsh/*.d.ts"],
      "*": ["./types/*.d.ts"]
    }
  },
  "files": [
    "./types/nsh/globals.d.ts",
    "./types/nsh/assets.d.ts",
    "./types/nsh/set-assets.d.ts",
    "./types/nsh/tokens.d.ts",
    "./types/nsh/roles.d.ts",
    "./types/nsh/modifiers.d.ts",
    "./types/nsh/translations.d.ts"
  ]
}
"#;

/// The bundler's files of `.nsh/types`.
pub fn type_definitions() -> Vec<(String, String)> {
    vec![("nsh/assets.d.ts".to_owned(), assets())]
}

/// The TypeScript type of a value of `value_type`, or `unknown` for a
/// token the active document doesn't declare: what `token()`, `role()` and
/// `tokens.get` of `nsh` give (`nsh_core::element::token_ts_type`).
fn ts_type(value_type: Option<nsh_core::element::ValueType>) -> &'static str {
    value_type.map_or("unknown", nsh_core::element::token_ts_type)
}

/// `tokens.d.ts`: the names of the app's design tokens `tokens` (those of
/// its active theme document: the app's, else its UI sets',
/// `bundle::AppTheme::tokens`), for `token()` of `nsh`, each typed by its
/// value type as TS reads it ([`ts_type`]) with its doc comment. Beside it, `interface
/// TokenKinds` gives each token's value type (`Tokens::kind_name`), for
/// `tokens.get`.
pub fn tokens_declaration(tokens: &nsh_core::element::Tokens) -> String {
    use std::fmt::Write as _;

    let mut names: Vec<&str> = tokens.names().collect();
    names.sort_unstable();
    names.dedup();
    let mut out = String::from(
        "// Generated by nsh from the active theme document: its design tokens.\nimport \"nsh\";\n\ndeclare module \"nsh\" {\n  interface Tokens {\n",
    );
    for name in &names {
        if let Some(doc) = tokens.doc_of(name).filter(|d| !d.is_empty()) {
            let _ = writeln!(out, "    /** {} */", doc.replace("*/", "*\\/"));
        }
        let _ = writeln!(out, "    {name:?}: {};", ts_type(tokens.kind_of(name)));
    }
    out.push_str("  }\n  interface TokenKinds {\n");
    for name in &names {
        if let Some(kind) = tokens.kind_name(name) {
            let _ = writeln!(out, "    {name:?}: {kind:?};");
        }
    }
    out.push_str("  }\n}\n");
    out
}

/// `modifiers.d.ts`: `ThemeModifiers`, the modifiers of the active theme
/// document of `tokens`, each with the union of its contexts' names as
/// string literals, for `setModifier()` and `modifier()` of `nsh`.
pub fn modifiers_declaration(tokens: &nsh_core::element::Tokens) -> String {
    use std::fmt::Write as _;
    let mut out = String::from(
        "// Generated by nsh from the active theme document: its modifiers and their contexts.\nimport \"nsh\";\n\ndeclare module \"nsh\" {\n  interface ThemeModifiers {\n",
    );
    for axis in tokens.modifiers() {
        let contexts: Vec<String> = axis.contexts.iter().map(|c| format!("{c:?}")).collect();
        let _ = writeln!(out, "    {:?}: {};", axis.name, contexts.join(" | "));
    }
    out.push_str("  }\n}\n");
    out
}

/// `roles.d.ts` for an app whose UI sets are `ui_sets`: the roles they
/// register and the core's own (`description::roles`), each typed by the
/// value type it reads ([`ts_type`]) with its doc comment, which says
/// whether it is required, for `role()` of `nsh`. `Err`: two sets list one
/// role reading different value types.
pub fn roles_declaration(
    ui_sets: &[nsh_core::element::description::SetDescription],
) -> Result<String, String> {
    use std::fmt::Write as _;
    let roles = nsh_core::element::description::roles(ui_sets)?;
    let mut out = String::from(
        "// Generated by nsh from the UI sets' roles: what `role()` names.\nimport \"nsh\";\n\ndeclare module \"nsh\" {\n  interface Roles {\n",
    );
    for role in roles {
        let doc = role
            .doc
            .as_deref()
            .map(|doc| doc.trim().replace("*/", "*\\/").replace('\n', " "))
            .filter(|doc| !doc.is_empty());
        let required = if role.required {
            "Required: every theme maps it."
        } else {
            "Optional: unmapped, it reads the token of its own name."
        };
        let doc = match doc {
            Some(doc) => format!("{doc} {required}"),
            None => required.to_owned(),
        };
        let _ = writeln!(out, "    /** {doc} */");
        let _ = writeln!(
            out,
            "    {:?}: {};",
            role.name,
            ts_type(Some(role.value_type))
        );
    }
    out.push_str("  }\n}\n");
    Ok(out)
}

/// `translations.d.ts`: the keys, `%{name}` parameters and locale tags of the
/// app's `locales/` directory, for `nsh/i18n`. When `translations` is empty (no
/// `locales/` directory), emits an empty module so `Translations` stays `{}`
/// and `t()` continues accepting any `string`.
pub fn translations_declaration(translations: &nsh_i18n::Translations) -> String {
    use std::{
        collections::{BTreeMap, BTreeSet},
        fmt::Write as _,
    };

    if translations.is_empty() {
        return "// Generated by nsh from `locales/`: no translations in this app.\nexport {};\n"
            .to_owned();
    }

    let mut keys: BTreeMap<&str, BTreeSet<String>> = BTreeMap::new();
    for messages in translations.values() {
        for (key, text) in messages {
            let params = keys.entry(key.as_str()).or_default();
            extract_placeholders(text, params);
        }
    }

    let mut out = String::from(
        "// Generated by nsh from `locales/`: the app's translation keys and parameters.\nimport \"nsh/i18n\";\n\ndeclare module \"nsh/i18n\" {\n  interface TranslationLocales {\n",
    );
    for locale in translations.keys() {
        let _ = writeln!(out, "    {locale:?}: true;");
    }
    out.push_str("  }\n");
    if !keys.is_empty() {
        out.push_str("  interface Translations {\n");
        for (key, params) in keys {
            if params.is_empty() {
                let _ = writeln!(out, "    {key:?}: Record<never, never>;");
            } else {
                let fields = params
                    .iter()
                    .map(|p| format!("{p:?}: string | number"))
                    .collect::<Vec<_>>()
                    .join("; ");
                let _ = writeln!(out, "    {key:?}: {{ {fields} }};");
            }
        }
        out.push_str("  }\n");
    }
    out.push_str("}\n");
    out
}

/// Inserts every valid `%{name}` interpolation parameter in `text` (excluding
/// `locale`, which `nsh/i18n` reserves for switching the lookup language).
fn extract_placeholders(text: &str, out: &mut std::collections::BTreeSet<String>) {
    let mut rest = text;
    while let Some(start) = rest.find("%{") {
        let after = &rest[start + 2..];
        let Some(end) = after.find('}') else {
            break;
        };
        let name = &after[..end];
        if !name.is_empty()
            && name != "locale"
            && name
                .bytes()
                .all(|b| b.is_ascii_alphanumeric() || b == b'_' || b == b'-')
        {
            out.insert(name.to_owned());
        }
        rest = &after[end + 1..];
    }
}

/// Checks `translations` across locales for missing keys (respecting BCP 47
/// parent-tag inheritance such as `zh-TW` -> `zh`) and mismatched `%{name}`
/// placeholders relative to `"en"` (or the first sorted locale when `"en"` is
/// absent).
pub fn translation_warnings(translations: &nsh_i18n::Translations) -> Vec<String> {
    use std::collections::{BTreeMap, BTreeSet};

    const MAX_LISTED_KEYS: usize = 5;

    if translations.len() < 2 {
        return Vec::new();
    }

    let base = if translations.contains_key("en") {
        "en"
    } else {
        translations
            .keys()
            .next()
            .map(String::as_str)
            .unwrap_or_default()
    };

    let mut reference: BTreeMap<&str, (&str, BTreeSet<String>)> = BTreeMap::new();
    for (locale, messages) in translations {
        for (key, text) in messages {
            let take = reference
                .get(key.as_str())
                .is_none_or(|(owner, _)| locale.as_str() == base && *owner != base);
            if take {
                let mut params = BTreeSet::new();
                extract_placeholders(text, &mut params);
                reference.insert(key.as_str(), (locale.as_str(), params));
            }
        }
    }

    let mut warnings = Vec::new();
    for (locale, messages) in translations {
        for (key, text) in messages {
            let Some(&(ref_locale, ref expected)) = reference.get(key.as_str()) else {
                continue;
            };
            if locale.as_str() == ref_locale {
                continue;
            }
            let mut actual = BTreeSet::new();
            extract_placeholders(text, &mut actual);
            if &actual != expected {
                warnings.push(format!(
                    "locales: `{locale}` key {key:?} has placeholders {} (expected {} from `{ref_locale}`)",
                    format_placeholders(&actual),
                    format_placeholders(expected),
                ));
            }
        }

        if has_parent_locale(translations, locale) {
            continue;
        }
        let missing: Vec<&str> = reference
            .keys()
            .copied()
            .filter(|k| !messages.contains_key(*k))
            .collect();
        if !missing.is_empty() {
            let shown: String = missing
                .iter()
                .take(MAX_LISTED_KEYS)
                .map(|k| format!("{k:?}"))
                .collect::<Vec<_>>()
                .join(", ");
            let tail = if missing.len() > MAX_LISTED_KEYS {
                format!(" (and {} more)", missing.len() - MAX_LISTED_KEYS)
            } else {
                String::new()
            };
            let noun = if missing.len() == 1 { "key" } else { "keys" };
            warnings.push(format!(
                "locales: `{locale}` is missing {} {noun}: {shown}{tail}",
                missing.len(),
            ));
        }
    }
    warnings
}

fn has_parent_locale(translations: &nsh_i18n::Translations, locale: &str) -> bool {
    let mut tag = locale;
    while let Some(cut) = tag.rfind(['-', '_']) {
        tag = &tag[..cut];
        if translations.contains_key(tag) {
            return true;
        }
    }
    false
}

fn format_placeholders(params: &std::collections::BTreeSet<String>) -> String {
    if params.is_empty() {
        return "none".to_owned();
    }
    params
        .iter()
        .map(|p| format!("`%{{{p}}}`"))
        .collect::<Vec<_>>()
        .join(", ")
}

/// `assets.d.ts`: what importing an image, a sound, a video, a font or any
/// file with `?url` gives (`plugin.rs`).
fn assets() -> String {
    use std::fmt::Write as _;
    let mut out = String::from("// Generated by nsh: what asset imports give.\n");
    for ext in crate::plugin::IMAGE_EXTENSIONS {
        let doc = match *ext {
            "svg" => "The SVG image, sized in points by its `width` and `height` (or `viewBox`).",
            _ => {
                "The image, sized in points (`@2x` files at half their pixels). Imported without a density suffix, its `@1.5x`–`@4x` siblings ship too (in `scales`) and the one for the screen loads."
            }
        };
        let _ = write!(
            out,
            "\ndeclare module \"*.{ext}\" {{\n  /** {doc} */\n  const asset: import(\"./types\").ImageAsset;\n  export default asset;\n}}\n"
        );
    }
    for ext in crate::plugin::AUDIO_EXTENSIONS {
        let _ = write!(
            out,
            "\ndeclare module \"*.{ext}\" {{\n  /** The audio file's URL (for `Sound.load` and `AudioPlayer`); the file ships with the app. */\n  const url: string;\n  export default url;\n}}\n"
        );
    }
    for ext in crate::plugin::VIDEO_EXTENSIONS {
        let _ = write!(
            out,
            "\ndeclare module \"*.{ext}\" {{\n  /** The video file's URL (for `Video`'s `src`); the file ships with the app. */\n  const url: string;\n  export default url;\n}}\n"
        );
    }
    let _ = write!(
        out,
        "\ndeclare module \"*{}\" {{\n  /** The file's `asset:/` URL (for `fetch` and the elements that take a URL); the file ships with the app. */\n  const url: string;\n  export default url;\n}}\n",
        crate::plugin::URL_SUFFIX
    );
    for ext in crate::plugin::FONT_EXTENSIONS {
        let _ = write!(
            out,
            "\ndeclare module \"*.{ext}\" {{\n  /** The font's family name (for `fontFamily`); the font is registered before the first frame. */\n  const family: string;\n  export default family;\n}}\n"
        );
    }
    out
}

/// `set-assets.d.ts`: the files the UI sets `ui_sets` ship
/// (`Registry::assets`), each declared by its URL
/// (`asset:/@<package>/<path>`) as importing it gives it
/// (`plugin/set_assets.rs`): an image an `ImageAsset`, a font its family
/// name, any other file its URL.
pub fn set_assets_declaration(
    ui_sets: &[nsh_core::element::description::SetDescription],
) -> String {
    use std::fmt::Write as _;
    let has = |path: &str, extensions: &[&str]| {
        std::path::Path::new(path)
            .extension()
            .and_then(|e| e.to_str())
            .is_some_and(|e| extensions.iter().any(|x| x.eq_ignore_ascii_case(e)))
    };
    let mut paths: Vec<String> = ui_sets
        .iter()
        .flat_map(|set| &set.assets)
        .map(|file| file.path.clone())
        .collect();
    // Also declare aliased logical paths from any package's `assets.toml`.
    for file in ui_sets.iter().flat_map(|set| &set.assets) {
        let Some(rest) = file.path.strip_prefix('@') else {
            continue;
        };
        let Some((pkg, rel)) = rest.split_once('/') else {
            continue;
        };
        if rel != "assets.toml" {
            continue;
        }
        if let Ok(text) = std::fs::read_to_string(&file.source)
            && let Ok(manifest) = nsh_core::element::AssetFilterManifest::parse(&text)
        {
            for entry in manifest.entries {
                if let Some(alias) = entry.alias {
                    let norm = nsh_core::element::asset_context::normalize_rel_path(&alias);
                    if !norm.is_empty() {
                        paths.push(format!("@{pkg}/{norm}"));
                    }
                }
            }
        }
    }
    paths.sort_unstable();
    paths.dedup();
    let mut out = String::from(
        "// Generated by nsh from the UI sets: the files they ship, as importing them gives them.\n",
    );
    for path in &paths {
        let name = serde_json::Value::String(format!("asset:/{path}")).to_string();
        let (value, ty) = if has(path, crate::plugin::IMAGE_EXTENSIONS) {
            ("asset", "import(\"./types\").ImageAsset")
        } else if has(path, crate::plugin::FONT_EXTENSIONS) {
            ("family", "string")
        } else {
            ("url", "string")
        };
        let _ = write!(
            out,
            "\ndeclare module {name} {{\n  const {value}: {ty};\n  export default {value};\n}}\n"
        );
    }
    out
}

