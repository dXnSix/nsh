//! The bundler's part of the TypeScript declarations of `.nsh/types` (the
//! rest is nsh's modules', from `nsh_js::type_definitions`): what the asset
//! imports the bundler loads give (`assets.d.ts`). Apps find them through
//! their `tsconfig.json` ([`TSCONFIG`], extending [`TSCONFIG_BASE`]) and
//! need no `node_modules`.

/// `tsconfig.json` of a new app (`nsh init`): nsh's settings come from
/// [`TSCONFIG_BASE`], which every command that builds the app writes to
/// `.nsh/tsconfig.json`, so a new `lib` or path reaches existing apps
/// without an edit of theirs; the app's own settings go here, over them.
pub const TSCONFIG: &str = r#"{
  "extends": "./.nsh/tsconfig.json",
  "include": ["**/*.ts", "**/*.tsx"]
}
"#;

/// `.nsh/tsconfig.json`, which the app's `tsconfig.json` ([`TSCONFIG`])
/// extends: resolves `nsh` and the app's own native modules (`nsh.json`
/// `"rust"`) to `.nsh/types` (other imports fall back to `node_modules`),
/// JSX to nsh's (`nsh/jsx-runtime`), and declares the globals and asset
/// imports. A shader's import finds its own declaration
/// ([`shader_declarations`]: `.nsh/types/app/<path>.d.wgsl.ts`, the app's
/// directory and `types/app` being one root). Paths and files are relative
/// to `.nsh`, where it is.
pub const TSCONFIG_BASE: &str = r#"// Generated by nsh, which keeps it current: the TypeScript settings of
// an nsh app. The app's tsconfig.json extends it; set your own there.
{
  "compilerOptions": {
    "target": "ES2023",
    "lib": ["ES2023", "ESNext.Disposable"],
    "module": "ESNext",
    "moduleResolution": "Bundler",
    "jsx": "preserve",
    "jsxImportSource": "nsh",
    "strict": true,
    "noEmit": true,
    "isolatedModules": true,
    "skipLibCheck": true,
    "types": [],
    "allowArbitraryExtensions": true,
    "rootDirs": ["..", "./types/app"],
    "paths": {
      "nsh": ["./types/nsh/index.d.ts"],
      "nsh/*": ["./types/nsh/*.d.ts"],
      "*": ["./types/*.d.ts"]
    }
  },
  "files": [
    "./types/nsh/globals.d.ts",
    "./types/nsh/assets.d.ts",
    "./types/nsh/tokens.d.ts"
  ]
}
"#;

/// The bundler's files of `.nsh/types`.
pub fn type_definitions() -> Vec<(String, String)> {
    vec![("nsh/assets.d.ts".to_owned(), assets())]
}

/// The declarations of the app's shaders (`.wgsl` files under `app`, the
/// app's directory): `app/<path>.d.wgsl.ts`, the shader's uniforms typed
/// from its source ([`TSCONFIG_BASE`] finds them). A shader that does not
/// compile is declared untyped (the build says why).
pub fn shader_declarations(app: &std::path::Path) -> Vec<(String, String)> {
    let mut files = Vec::new();
    shader_files(app, app, &mut files);
    files.sort();
    files
        .into_iter()
        .map(|rel| {
            let source = std::fs::read_to_string(app.join(&rel)).unwrap_or_default();
            let declaration = shader_declaration(&rel, &source);
            let stem = rel.strip_suffix(".wgsl").unwrap_or(&rel);
            (format!("app/{stem}.d.wgsl.ts"), declaration)
        })
        .collect()
}

/// The `.wgsl` files under `dir`, relative to `app` (with `/`); dot
/// directories, `node_modules` and `target` are not the app's.
fn shader_files(app: &std::path::Path, dir: &std::path::Path, out: &mut Vec<String>) {
    let Ok(entries) = std::fs::read_dir(dir) else {
        return;
    };
    for entry in entries.flatten() {
        let path = entry.path();
        let name = entry.file_name().to_string_lossy().into_owned();
        if path.is_dir() {
            if !name.starts_with('.') && name != "node_modules" && name != "target" {
                shader_files(app, &path, out);
            }
        } else if crate::plugin::SHADER_EXTENSIONS
            .iter()
            .any(|e| path.extension().is_some_and(|x| x.eq_ignore_ascii_case(e)))
            && let Ok(rel) = path.strip_prefix(app)
        {
            out.push(
                rel.components()
                    .map(|c| c.as_os_str().to_string_lossy())
                    .collect::<Vec<_>>()
                    .join("/"),
            );
        }
    }
}

/// The declaration of shader `rel` (`source`): its default export is a
/// `ShaderAsset` of its uniforms.
fn shader_declaration(rel: &str, source: &str) -> String {
    use std::fmt::Write as _;

    use nsh_core::shader::UniformType as U;
    let mut out = format!(
        "// Generated by nsh from {rel}: its uniforms.
"
    );
    let shader = match nsh_core::shader::compile(source, &nsh_core::shader::ShaderLimits::default())
    {
        Ok(shader) => shader,
        Err(_) => {
            out.push_str(
                "declare const shader: import(\"nsh\").ShaderAsset;\nexport default shader;\n",
            );
            return out;
        }
    };
    const N: &str = "import(\"nsh\").ShaderNumber";
    let tuple = |n: usize, item: &str| format!("readonly [{}]", vec![item; n].join(", "));
    let mut fields = String::new();
    for u in &shader.reflection().uniforms {
        let element = match u.ty {
            U::F32 => N.to_string(),
            U::I32 => "number".into(),
            U::Vec2 => format!(
                "{} | import(\"nsh\").Point | import(\"nsh\").Size | {N}",
                tuple(2, N)
            ),
            U::Vec3 => format!("{} | string | {N}", tuple(3, N)),
            U::Vec4 => format!("{} | string | {N}", tuple(4, N)),
            U::IVec2 => tuple(2, "number"),
            U::IVec3 => tuple(3, "number"),
            U::IVec4 => tuple(4, "number"),
            U::Mat2 => tuple(4, "number"),
            U::Mat3 => tuple(9, "number"),
            U::Mat4 => tuple(16, "number"),
            U::Image(_) => "import(\"nsh\").ImageAsset | string".into(),
        };
        let ty = match u.count {
            Some(_) => format!("readonly ({element})[]"),
            None => element,
        };
        let _ = writeln!(fields, "  {}?: {ty};", u.name);
    }
    let _ = write!(
        out,
        "declare const shader: import(\"nsh\").ShaderAsset<{{\n{fields}}}>;\nexport default shader;\n"
    );
    out
}

/// `tokens.d.ts`: the names of the app's design tokens `tokens` (its
/// theme's over the default's), for `token()` of `nsh`.
pub fn tokens_declaration(tokens: &nsh_core::ui::Tokens) -> String {
    use std::fmt::Write as _;
    let mut names: Vec<(&str, &str)> = tokens
        .colors()
        .map(|(n, _)| (n, "string"))
        .chain(tokens.numbers().map(|(n, _)| (n, "number")))
        .chain(tokens.fonts().map(|(n, _)| (n, "string")))
        .collect();
    names.sort_unstable();
    names.dedup_by_key(|(n, _)| *n);
    let mut out = String::from(
        "// Generated by nsh from nsh.json's \"theme\": the app's design tokens.\nimport \"nsh\";\n\ndeclare module \"nsh\" {\n  interface Tokens {\n",
    );
    for (name, ty) in names {
        let _ = writeln!(out, "    {name:?}: {ty};");
    }
    out.push_str("  }\n}\n");
    out
}

/// `assets.d.ts`: what importing an image or a font gives (`plugin.rs`).
fn assets() -> String {
    use std::fmt::Write as _;
    let mut out = String::from("// Generated by nsh: what asset imports give.\n");
    for ext in crate::plugin::IMAGE_EXTENSIONS {
        let doc = match *ext {
            "svg" => "The SVG image, sized in points by its `width` and `height` (or `viewBox`).",
            _ => {
                "The image, sized in points (`@2x` files at half their pixels). Imported without a density suffix, its `@1.5x`–`@4x` siblings ship too (in `scales`) and the one for the screen loads."
            }
        };
        let _ = write!(
            out,
            "\ndeclare module \"*.{ext}\" {{\n  /** {doc} */\n  const asset: import(\"./types\").ImageAsset;\n  export default asset;\n}}\n"
        );
    }
    for ext in crate::plugin::FONT_EXTENSIONS {
        let _ = write!(
            out,
            "\ndeclare module \"*.{ext}\" {{\n  /** The font's family name (for `fontFamily`); the font is registered before the first frame. */\n  const family: string;\n  export default family;\n}}\n"
        );
    }
    for ext in crate::plugin::SHADER_EXTENSIONS {
        let _ = write!(
            out,
            "\ndeclare module \"*.{ext}\" {{\n  /** The shader (WGSL in NSH's profile), checked when the app is built; its uniforms are typed in its own declaration. */\n  const shader: import(\"./types\").ShaderAsset;\n  export default shader;\n}}\n"
        );
    }
    out
}

#[cfg(test)]
mod tests {
    #[test]
    fn shader_imports_are_typed_from_their_uniforms() {
        let declaration = super::shader_declaration(
            "fx/glass.wgsl",
            "struct U { tint: vec4f, radius: f32, photo: Image, weights: array<vec4f, 2> }\nfn main(p: vec2f, u: U) -> vec4f { return u.tint * u.radius + u.weights[0] + sample_image(u.photo, p); }",
        );
        assert!(
            declaration.contains("// Generated by nsh from fx/glass.wgsl"),
            "{declaration}"
        );
        assert!(
            declaration.contains("  tint?: readonly [import(\"nsh\").ShaderNumber"),
            "{declaration}"
        );
        assert!(
            declaration.contains("  radius?: import(\"nsh\").ShaderNumber;"),
            "{declaration}"
        );
        assert!(
            declaration.contains("  photo?: import(\"nsh\").ImageAsset | string;"),
            "{declaration}"
        );
        assert!(
            declaration.contains("  weights?: readonly ("),
            "{declaration}"
        );
        // One that does not compile is untyped.
        let untyped = super::shader_declaration("bad.wgsl", "fn main() {}");
        assert!(untyped.contains("ShaderAsset;"), "{untyped}");
    }

    #[test]
    fn asset_imports_are_declared() {
        let assets = super::assets();
        assert!(assets.contains("declare module \"*.png\""));
        assert!(assets.contains("declare module \"*.ttf\""));
    }

    #[test]
    fn svg_import_is_declared() {
        let assets = super::assets();
        let svg = assets
            .split("\ndeclare module ")
            .find(|d| d.starts_with("\"*.svg\""))
            .expect("*.svg is declared");
        assert!(svg.contains("ImageAsset"), "{svg}");
        assert!(svg.contains("The SVG image, sized in points"), "{svg}");
        assert!(!svg.contains("@2x"), "{svg}");
    }

    #[test]
    fn variant_types_image_modules_describe_variants() {
        let assets = super::assets();
        for ext in crate::plugin::IMAGE_EXTENSIONS
            .iter()
            .filter(|e| **e != "svg")
        {
            let module = format!("declare module \"*.{ext}\" {{");
            let at = assets.find(&module).expect(ext);
            let block = &assets[at..at + assets[at..].find("\n}\n").unwrap()];
            assert!(
                block.contains("its `@1.5x`–`@4x` siblings ship too (in `scales`)"),
                "{block}"
            );
            assert!(block.contains("import(\"./types\").ImageAsset"), "{block}");
        }
    }
}
