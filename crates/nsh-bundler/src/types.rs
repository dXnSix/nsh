//! The bundler's part of the TypeScript declarations of `.nsh/types` (the
//! rest is nsh's modules', from `nsh_js::type_definitions`): what the asset
//! imports the bundler loads give (`assets.d.ts`). Apps find them through
//! their `tsconfig.json` ([`TSCONFIG`], extending [`TSCONFIG_BASE`]) and
//! need no `node_modules`.

/// `tsconfig.json` of a new app (`nsh init`): nsh's settings come from
/// [`TSCONFIG_BASE`], which every command that builds the app writes to
/// `.nsh/tsconfig.json`, so a new `lib` or path reaches existing apps
/// without an edit of theirs; the app's own settings go here, over them.
pub const TSCONFIG: &str = r#"{
  "extends": "./.nsh/tsconfig.json",
  "include": ["**/*.ts", "**/*.tsx"]
}
"#;

/// `.nsh/tsconfig.json`, which the app's `tsconfig.json` ([`TSCONFIG`])
/// extends: resolves `nsh` and the app's own native modules (`nsh.json`
/// `"rust"`) to `.nsh/types` (other imports fall back to `node_modules`),
/// JSX to nsh's (`nsh/jsx-runtime`), and declares the globals and asset
/// imports. Paths and files are relative to `.nsh`, where it is.
pub const TSCONFIG_BASE: &str = r#"// Generated by nsh, which keeps it current: the TypeScript settings of
// an nsh app. The app's tsconfig.json extends it; set your own there.
{
  "compilerOptions": {
    "target": "ES2023",
    "lib": ["ES2023", "ESNext.Disposable"],
    "module": "ESNext",
    "moduleResolution": "Bundler",
    "jsx": "preserve",
    "jsxImportSource": "nsh",
    "strict": true,
    "noEmit": true,
    "isolatedModules": true,
    "skipLibCheck": true,
    "types": [],
    "paths": {
      "nsh": ["./types/nsh/index.d.ts"],
      "nsh/*": ["./types/nsh/*.d.ts"],
      "*": ["./types/*.d.ts"]
    }
  },
  "files": [
    "./types/nsh/globals.d.ts",
    "./types/nsh/assets.d.ts",
    "./types/nsh/tokens.d.ts",
    "./types/nsh/roles.d.ts",
    "./types/nsh/modifiers.d.ts"
  ]
}
"#;

/// The bundler's files of `.nsh/types`.
pub fn type_definitions() -> Vec<(String, String)> {
    vec![("nsh/assets.d.ts".to_owned(), assets())]
}

/// `tokens.d.ts`: the names of the app's design tokens `tokens` (those of
/// its active theme document), for `token()` of `nsh`, each typed by its
/// value type (a number, a boolean, or a string: a color, a font family, a
/// shadow's CSS) with its doc comment. Beside it, `interface TokenKinds`
/// gives each token's value type (`Tokens::kind_name`), for `tokens.get`.
pub fn tokens_declaration(tokens: &nsh_core::element::Tokens) -> String {
    use std::fmt::Write as _;

    use nsh_core::element::ValueType;
    let mut names: Vec<&str> = tokens.names().collect();
    names.sort_unstable();
    names.dedup();
    let mut out = String::from(
        "// Generated by nsh from the app's theme document: its design tokens.\nimport \"nsh\";\n\ndeclare module \"nsh\" {\n  interface Tokens {\n",
    );
    for name in &names {
        if let Some(doc) = tokens.doc_of(name).filter(|d| !d.is_empty()) {
            let _ = writeln!(out, "    /** {} */", doc.replace("*/", "*\\/"));
        }
        let ty = match tokens.kind_of(name) {
            Some(ValueType::Boolean) => "boolean",
            Some(ValueType::Number | ValueType::Duration) => "number",
            _ => "string",
        };
        let _ = writeln!(out, "    {name:?}: {ty};");
    }
    out.push_str("  }\n  interface TokenKinds {\n");
    for name in &names {
        if let Some(kind) = tokens.kind_name(name) {
            let _ = writeln!(out, "    {name:?}: {kind:?};");
        }
    }
    out.push_str("  }\n}\n");
    out
}

/// `modifiers.d.ts`: the theme modifiers of the app's tokens `tokens`, each
/// with the union of its contexts' names, for `setModifier()` and
/// `modifier()` of `nsh`.
pub fn modifiers_declaration(tokens: &nsh_core::element::Tokens) -> String {
    use std::fmt::Write as _;
    let mut out = String::from(
        "// Generated by nsh from the app's theme: its modifiers and their contexts.\nimport \"nsh\";\n\ndeclare module \"nsh\" {\n  interface ThemeModifiers {\n",
    );
    for axis in tokens.modifiers() {
        let contexts: Vec<String> = axis.contexts.iter().map(|c| format!("{c:?}")).collect();
        let _ = writeln!(out, "    {:?}: {};", axis.name, contexts.join(" | "));
    }
    out.push_str("  }\n}\n");
    out
}

/// `roles.d.ts` for an app whose UI sets are `ui_sets`: the roles they list
/// and the core's own (`description::roles`), each typed by what it reads
/// (a number, or a string: a color, a font family) with its doc comment,
/// for `role()` of `nsh`. `Err`: two sets list one role reading different
/// kinds.
pub fn roles_declaration(
    ui_sets: &[nsh_core::element::description::SetDescription],
) -> Result<String, String> {
    use std::fmt::Write as _;
    let roles = nsh_core::element::description::roles(ui_sets)?;
    let mut out = String::from(
        "// Generated by nsh from the UI sets' roles: what `role()` names.\nimport \"nsh\";\n\ndeclare module \"nsh\" {\n  interface Roles {\n",
    );
    for role in roles {
        if !role.doc.is_empty() {
            let doc = role.doc.replace("*/", "*\\/").replace('\n', " ");
            let _ = writeln!(out, "    /** {doc} */");
        }
        let ty = if role.kind == "number" {
            "number"
        } else {
            "string"
        };
        let _ = writeln!(out, "    {:?}: {ty};", role.name);
    }
    out.push_str("  }\n}\n");
    Ok(out)
}

/// `assets.d.ts`: what importing an image, a sound, a video, a font or any
/// file with `?url` gives (`plugin.rs`).
fn assets() -> String {
    use std::fmt::Write as _;
    let mut out = String::from("// Generated by nsh: what asset imports give.\n");
    for ext in crate::plugin::IMAGE_EXTENSIONS {
        let doc = match *ext {
            "svg" => "The SVG image, sized in points by its `width` and `height` (or `viewBox`).",
            _ => {
                "The image, sized in points (`@2x` files at half their pixels). Imported without a density suffix, its `@1.5x`–`@4x` siblings ship too (in `scales`) and the one for the screen loads."
            }
        };
        let _ = write!(
            out,
            "\ndeclare module \"*.{ext}\" {{\n  /** {doc} */\n  const asset: import(\"./types\").ImageAsset;\n  export default asset;\n}}\n"
        );
    }
    for ext in crate::plugin::AUDIO_EXTENSIONS {
        let _ = write!(
            out,
            "\ndeclare module \"*.{ext}\" {{\n  /** The audio file's URL (for `Sound.load` and `AudioPlayer`); the file ships with the app. */\n  const url: string;\n  export default url;\n}}\n"
        );
    }
    for ext in crate::plugin::VIDEO_EXTENSIONS {
        let _ = write!(
            out,
            "\ndeclare module \"*.{ext}\" {{\n  /** The video file's URL (for `Video`'s `src`); the file ships with the app. */\n  const url: string;\n  export default url;\n}}\n"
        );
    }
    let _ = write!(
        out,
        "\ndeclare module \"*{}\" {{\n  /** The file's `asset:/` URL (for `fetch` and the elements that take a URL); the file ships with the app. */\n  const url: string;\n  export default url;\n}}\n",
        crate::plugin::URL_SUFFIX
    );
    for ext in crate::plugin::FONT_EXTENSIONS {
        let _ = write!(
            out,
            "\ndeclare module \"*.{ext}\" {{\n  /** The font's family name (for `fontFamily`); the font is registered before the first frame. */\n  const family: string;\n  export default family;\n}}\n"
        );
    }
    out
}

#[cfg(test)]
mod tests {
    #[test]
    fn asset_imports_are_declared() {
        let assets = super::assets();
        assert!(assets.contains("declare module \"*.png\""));
        assert!(assets.contains("declare module \"*.ttf\""));
        assert!(assets.contains("declare module \"*.wav\""));
        assert!(assets.contains("declare module \"*.woff2\""));
        assert!(assets.contains("declare module \"*.mp4\""));
        assert!(assets.contains("declare module \"*?url\""));
    }

    #[test]
    fn svg_import_is_declared() {
        let assets = super::assets();
        let svg = assets
            .split("\ndeclare module ")
            .find(|d| d.starts_with("\"*.svg\""))
            .expect("*.svg is declared");
        assert!(svg.contains("ImageAsset"), "{svg}");
        assert!(svg.contains("The SVG image, sized in points"), "{svg}");
        assert!(!svg.contains("@2x"), "{svg}");
    }

    #[test]
    fn variant_types_image_modules_describe_variants() {
        let assets = super::assets();
        for ext in crate::plugin::IMAGE_EXTENSIONS
            .iter()
            .filter(|e| **e != "svg")
        {
            let module = format!("declare module \"*.{ext}\" {{");
            let at = assets.find(&module).expect(ext);
            let block = &assets[at..at + assets[at..].find("\n}\n").unwrap()];
            assert!(
                block.contains("its `@1.5x`–`@4x` siblings ship too (in `scales`)"),
                "{block}"
            );
            assert!(block.contains("import(\"./types\").ImageAsset"), "{block}");
        }
    }
}

/// Shadow tokens are typed in `tokens.d.ts` as the CSS `token()` gives.
#[cfg(test)]
mod shadow_tokens {
    #[test]
    fn shadow_tokens_are_strings() {
        let tokens = super::tests_support::tokens_of(
            r##"{ "tokens": {
                "shadow-raised": { "kind": "shadow", "value": [{ "color": "#00000000" }] },
                "radius": { "kind": "number", "value": 10 }
            } }"##,
        );
        let declaration = super::tokens_declaration(&tokens);
        assert!(
            declaration.contains("    \"shadow-raised\": string;"),
            "{declaration}"
        );
        assert!(
            declaration.contains("    \"radius\": number;"),
            "{declaration}"
        );
    }
}

/// `roles.d.ts` names the roles the UI sets list, for `role()`.
#[cfg(test)]
mod role_declarations {
    use nsh_core::element::{NumberRole, Registry, Role, RoleSpec, description::SetDescription};

    fn described(roles: Vec<RoleSpec>) -> SetDescription {
        let mut set = Registry::ui_set("test/kit");
        set.roles(roles);
        SetDescription::of(&set).unwrap()
    }

    #[test]
    fn roles_are_typed_by_what_they_read_with_their_docs() {
        let kit = described(vec![
            RoleSpec::new(
                Role::<nsh_core::Hsla>::new("banner"),
                " A banner's */ surface.\n",
            ),
            RoleSpec::new(NumberRole::new("chip-radius"), ""),
        ]);
        let declaration = super::roles_declaration(&[kit]).unwrap();
        assert!(
            declaration.contains("declare module \"nsh\" {\n  interface Roles {\n"),
            "{declaration}"
        );
        // A set's own, with its doc (a comment's end escaped).
        assert!(
            declaration.contains("    /** A banner's *\\/ surface. */\n    \"banner\": string;\n"),
            "{declaration}"
        );
        assert!(
            declaration.contains("    \"chip-radius\": number;\n"),
            "{declaration}"
        );
        // The core's are always there.
        assert!(
            declaration.contains(
                "    /** Popovers, menus, tooltips, alerts. */\n    \"popover\": string;\n"
            ),
            "{declaration}"
        );
        assert!(
            declaration.contains("    \"font-sans\": string;\n"),
            "{declaration}"
        );
        // Without sets, the core's alone.
        let core = super::roles_declaration(&[]).unwrap();
        assert!(
            core.contains("\"primary\": string;") && !core.contains("banner"),
            "{core}"
        );
    }

    #[test]
    fn a_role_of_two_kinds_is_an_error() {
        let a = described(vec![RoleSpec::new(NumberRole::new("banner"), "")]);
        let mut other = Registry::ui_set("test/other");
        other.roles([RoleSpec::new(Role::<nsh_core::Hsla>::new("banner"), "")]);
        let b = SetDescription::of(&other).unwrap();
        let error = super::roles_declaration(&[a, b]).unwrap_err();
        assert_eq!(
            error,
            "the role `banner` is listed reading number and color"
        );
    }
}

