/// Tokens for the tests: those of a theme document.
#[cfg(test)]
pub(crate) mod tests_support {
    /// The tokens of theme document `json`, its default contexts picked.
    pub(crate) fn tokens_of(json: &str) -> nsh_core::element::Tokens {
        let document = nsh_theme::read(json).document;
        nsh_core::element::Tokens::resolve(
            std::sync::Arc::new(document),
            Default::default(),
            Vec::new(),
        )
        .0
    }
}
